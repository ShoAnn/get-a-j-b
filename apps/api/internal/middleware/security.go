package middleware

import (
	"net/http"
)

// SecurityHeaders sets baseline hardening headers for all responses.
// Content-Security-Policy is intentionally omitted here: this is a JSON API
// with no HTML rendering, so frame/content-type protections suffice.
func SecurityHeaders(next http.Handler) http.Handler {
	return http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) {
		w.Header().Set("X-Content-Type-Options", "nosniff")
		w.Header().Set("X-Frame-Options", "DENY")
		w.Header().Set("Referrer-Policy", "no-referrer")
		w.Header().Set("Permissions-Policy", "camera=(), microphone=(), geolocation=()")
		next.ServeHTTP(w, r)
	})
}

// MaxBodyBytes caps request body size to blunt oversized-payload DoS.
// 1 MiB is generous for this JSON API (jobs/resumes/auth payloads are small).
func MaxBodyBytes(n int64) func(http.Handler) http.Handler {
	return func(next http.Handler) http.Handler {
		return http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) {
			if r.Body != nil {
				r.Body = http.MaxBytesReader(w, r.Body, n)
			}
			next.ServeHTTP(w, r)
		})
	}
}
